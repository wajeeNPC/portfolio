// Copies the Solar icons the site uses into src/icons/solar-data.ts, so icons ship with the site
// and never load from the web. Run after changing ICONS:  node scripts/build-solar-icons.mjs
// Needs the dev dependency @iconify-json/solar (only used here, never bundled).
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const set = JSON.parse(readFileSync(require.resolve('@iconify-json/solar/icons.json'), 'utf8'))

// Our name -> Solar name. Linear (outlined) style.
const ICONS = {
  // Status tags and form labels
  BookOpen: 'book-2-linear',
  BookCheck: 'bookmark-check-linear',
  Bookmark: 'bookmark-linear',
  User: 'user-linear',
  UserRound: 'user-rounded-linear',
  Mail: 'letter-linear',
  MessageSquare: 'chat-square-linear',
  MessageCircle: 'chat-round-dots-linear',
  Send: 'plain-linear',
  // Actions
  Check: 'check-circle-linear',
  Copy: 'copy-linear',
  Download: 'download-minimalistic-linear',
  ArrowRight: 'arrow-right-linear',
  ChevronLeft: 'alt-arrow-left-linear',
  ChevronRight: 'alt-arrow-right-linear',
  X: 'close-circle-linear',
  // Media
  Play: 'play-linear',
  Pause: 'pause-linear',
  RotateCcw: 'restart-linear',
  Volume2: 'volume-loud-linear',
  VolumeX: 'volume-cross-linear',
  // Theme
  Sun: 'sun-linear',
  Moon: 'moon-linear',
  // Sections, projects and lab
  Briefcase: 'case-minimalistic-linear',
  FlaskConical: 'test-tube-linear',
  Newspaper: 'notebook-linear',
  Bot: 'cpu-bolt-linear',
  Cpu: 'cpu-linear',
  Gauge: 'chart-2-linear',
  Plug: 'plug-circle-linear',
  Building2: 'buildings-2-linear',
  FileSearch: 'document-text-linear',
  Sparkles: 'stars-linear',
  Clover: 'stars-minimalistic-linear',
  // Stack chips without a brand logo
  Tuning: 'tuning-2-linear',
  Layers: 'layers-minimalistic-linear',
  Transmission: 'transmission-linear',
}

const resolve = (name) => {
  const alias = set.aliases?.[name]
  return set.icons[name] ?? (alias && set.icons[alias.parent])
}

const missing = Object.entries(ICONS).filter(([, name]) => !resolve(name))
if (missing.length) {
  console.error('Not in Solar:', missing.map(([k, n]) => `${k} -> ${n}`).join(', '))
  process.exit(1)
}

const width = set.width ?? 24
const height = set.height ?? 24
const lines = Object.entries(ICONS).map(([key, name]) => {
  const icon = resolve(name)
  return `  ${key}: { body: ${JSON.stringify(icon.body)}, width: ${icon.width ?? width}, height: ${icon.height ?? height} },`
})

writeFileSync(
  new URL('../src/icons/solar-data.ts', import.meta.url),
  `// Generated by scripts/build-solar-icons.mjs from Solar (480 Design, CC BY 4.0). Do not edit by hand.\n` +
    `export const SOLAR = {\n${lines.join('\n')}\n} as const\n`,
)
console.log(`Wrote ${lines.length} icons`)
